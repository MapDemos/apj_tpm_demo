/**
 * L2 System Prompt (geonator_lite) — unified category-validity + name-relevance check
 * in a single LLM call (spec §6.1). Forked from geonator/prompts/prompt-l2.js, merging
 * PROMPT_L2_1 (category validity, poi_category/class-based) and PROMPT_L2_2 (name
 * relevance, 4-level) into one PROMPT_L2.
 *
 * PROMPT_L2_BUILDING is a name-only variant used for category_mansion/apartment/building
 * targets, where Tilequery's `class` is always 'building' and carries no discriminating
 * signal — the category-domain half of PROMPT_L2 is dropped, only name-relevance remains.
 *
 * The coordinate-cluster dedup step (formerly an LLM call using PROMPT_L2_DEDUP) is now a
 * deterministic normalized-name substring check in query-engine.js's _dedupClusters — no
 * prompt needed.
 */

const PROMPT_L2 = `各候補が「意図に合致し得るか」を4段階で判定してください。各候補には name（名前）と、分かる場合は poi_category（Search Box由来のカテゴリ配列）／class（Tilequery由来のカテゴリ）が付きます。目的は**明らかに種類が違うノイズを除くこと**であり、細かい下位種別まで厳密に絞ることではありません。

判定は2つの観点を**同時に**見て行います：
1. **カテゴリの大分類（分野）が明確に違うか**：飲食／物販・小売／宿泊／医療／金融／公共施設／教育／交通／自然・公園／事業所・オフィス／住居 等の分野で、意図と候補のpoi_category/classが明確に異なる分野なら、それだけでnoの根拠になり得る（例：意図「公園」に対しpoi_category=「銀行」)。同じ分野の中の下位・隣接カテゴリ、または曖昧・上位すぎて分野が判断できないカテゴリは、この観点だけではnoにしない。
2. **名前から確定的に違うと分かるか**：最重要の非対称ルール（これを最優先）——**名前から"確定的に違う"と分かるものだけを名前の観点でno にする。** 名前から分からない差（下位種別・属性・設備・専門性の有無）では no にしない＝残す。
   - なぜ非対称か：**ブランド/チェーンは名前で確定できる**（「ファミリーマート」は名前でローソンでないと確定→no）。一方**属性・下位種別は名前に出ないことが多い**（「GOLD'S GYM」の名前だけではクロスフィット提供の有無は分からない→残す）。

no（除外）にするのは次のいずれかに該当する場合**だけ**:
a. **カテゴリの分野が意図と明確に異なる**（poi_category/classが分かっている場合のみ判断材料にする。分からない/曖昧なら分野だけでnoにしない）。
b. **名前が示す"主たる用途/業態"が意図と別**：意図と種類が明確に違う（意図ジム→歯科/寺/駅/レストラン）。
   - **意図語を名前に含んでも、名前が別の主用途を示すなら no**。判定は「その施設の**主目的は何か**」：
     - 意図「公園」→「○○公園**駅前店**」「○○公園**前店**」= 主用途は**店**（コンビニ等）→ no（公園ではない）。「○○公園」= 公園 → 残す。
     - 意図「ジム」→「○○**小学校**体育館」「○○中学校グラウンド」= 主用途は**学校施設** → no。「○○フィットネス/○○ジム」= 主用途フィットネス → 残す。
     - 一般化：名前に「〜駅前店/〜前店/〜支店」（店）・「〜小学校/中学校/高校/大学」（学校）・「〜市役所/区役所」（役所）等、**別業態を明示する語**があれば、意図語を含んでいても no。
     - **住居形態の混同にも同じ原則を適用する**：意図「マンション」に対し、名前に「アパート」と明記された候補（例：「◇◇アパート」）は主用途が異なる建て方＝no。ただし名前が「レジデンス/ハイツ/コーポ/コート」等の一般的な集合住宅名で、アパートともマンションとも確定できない場合は下記のprobably/unknownのまま残す。
     - **総合小売と単一品目専門店の混同にも同じ原則を適用する**：意図「スーパー」（複数品目を扱う総合的な食料品店）に対し、名前が単一品目に特化した専門小売（青果店・八百屋・精肉店・鮮魚店・酒屋・米屋等）であることを明示している場合は主用途が異なる＝no（例：意図スーパー→「青果おおさか屋」「○○精肉店」=no。総合スーパーではなく専門小売）。ただし「マーケット」「ストア」等どちらとも確定できない一般的な名前はprobably/unknownのまま残す。
     - **逆に「別業態を明示する語」と誤認してはいけない例**：「アネックス/別館/新館/本館/別棟」等は**同じ施設の別の建物**を指すだけで、別業態でも別施設でもない。意図「ホテル」に対し「○○ホテルアネックス」「○○ホテル別館」は本体と同じホテルなので**no にしない**（本体と同じ扱いでdefinitely/probably）。これらの語だけを理由にnoにするのは誤り——noにするのは「レストラン/カフェ/駐車場/宴会場」等、**実際に業態そのものが変わる語**がある時だけ（例：「○○ホテルレストラン△△」は主用途がレストランなのでno、「○○ホテルアネックス」は主用途が変わらずホテルなので残す）。
c. **名前で確定できる別ブランド/別チェーン**：意図が特定ブランドで、候補名が別ブランドと**名前から確定**（意図ローソン→「ファミリーマート」=no）。
d. **種別を"扱うだけ"の別業態**（意図が場所/建物種別の時）：意図マンション→「◇◇不動産／賃貸仲介」=no（その物件でなく仲介業者）。
e. **名前が既に廃止・他チェーンへ統合済みの旧ブランドを示す**（例：サークルKサンクス〈ファミリーマートに統合済み〉、スリーエフ〈ローソングループに統合済み〉等）→no。実店舗として現存しない可能性が高い旧ブランド名の候補は、意図が何であれ除外する。ただし**意図自体がその旧ブランド名を名指ししている場合はこの限りではない**（その時はno にしない）。

上記以外は **no にしない**。特に**同じカテゴリ内で下位種別・属性が名前から確定できない候補は必ず残す**（definitely/probably/unknown のいずれか）。全件 no にして0件にしない。

4段階:
- definitely: 意図そのものだと確実（例:意図スーパー→マルエツ/イオン、意図ローソン→ローソン各店、意図クロスフィットジム→名前に「クロスフィット/CrossFit」がある店）
- probably: 意図の可能性が高い（例:意図マンション→○○レジデンス、**意図クロスフィットジム→GOLD'S GYM/エニタイム等の一般ジム**＝ジムなので合致し得る）
- unknown（既定・未記載扱い）: 判断つかない/名前もカテゴリも一般的/不明
- no（除外）: 上記「no にする5つ」に該当するものだけ

迷ったら unknown（残す）。「属性/下位種別が名前で確認できない」だけでは絶対に no にしない。「業者だから一律 no」にもしない。

例）意図「クロスフィットジム」で GOLD'S GYM・エニタイム・セントラルフィットネス・○○パーソナルジム 等は**すべて probably か unknown（残す）**。no にするのは歯科・寺・レストラン等の別カテゴリのみ。

出力はJSONのみ（前後に説明文なし）。definitely/probably/no の id 配列だけ。unknownは列挙不要。該当なしは空配列:
\`\`\`json
{"definitely": [1, 5], "probably": [2], "no": [3, 9]}
\`\`\`
`;

